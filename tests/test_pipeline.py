def test_pending_ignores_dotfiles_reason_files_and_folders(tmp_path):
    layout = layout_in(tmp_path)
    (layout.inbox / "a.yaml").write_text("x", encoding="utf-8")
    (layout.inbox / ".hidden").write_text("x", encoding="utf-8")
    (layout.inbox / "a.reason.txt").write_text("x", encoding="utf-8")
    (layout.inbox / "review").mkdir()
    assert [p.name for p in pending(layout, settle_s=0)] == ["a.yaml"]


def test_watch_once_processes_everything_waiting(tmp_path):
    layout = layout_in(tmp_path)
    drop(layout.inbox, spec_with("pipewatch", read_op(confidence=0.3)))  # blocked -> fast, no generation
    junk = layout.inbox / "junk.json"
    junk.write_text("[1]", encoding="utf-8")
    outcomes = watch(layout, once=True)
    assert sorted(o.status for o in outcomes) == ["failed", "review"]
    assert pending(layout, settle_s=0) == []
