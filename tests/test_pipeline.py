# -- detection -----------------------------------------------------------------------------------

@pytest.mark.parametrize("filename,content,expected", [
    ("a.json", json.dumps({"openapi": "3.0.0", "info": {}, "paths": {}}), "openapi"),
    ("a.yaml", "swagger: '2.0'\ninfo: {}\npaths: {}\n", "openapi"),
    ("a.har", json.dumps({"log": {"entries": []}}), "trace"),
    ("a.json", json.dumps({"log": {"entries": []}}), "trace"),
    ("a.json", json.dumps([{"request": {"method": "GET", "url": "https://x.test/a"}, "response": {"status": 200}}]), "trace"),
    ("a.md", "# API docs\nGET /things", "doc"),
    ("a.txt", "GET /things", "doc"),
    ("a.yaml", "system_name: x\noperations: []\n", "spec"),
])
def test_detect_type(tmp_path, filename, content, expected):
    path = tmp_path / filename
    path.write_text(content, encoding="utf-8")
    assert detect_type(path) == expected


@pytest.mark.parametrize("filename,content", [("a.json", '{"hello": 1}'), ("a.bin", "x"), ("a.json", "[1, 2]")])
def test_undetectable_input_is_rejected(tmp_path, filename, content):
    path = tmp_path / filename
    path.write_text(content, encoding="utf-8")
    with pytest.raises(ValueError, match="cannot detect"):
        detect_type(path)


# -- success path --------------------------------------------------------------------------------

def test_clean_read_spec_is_generated_verified_and_promoted(tmp_path):
    layout = layout_in(tmp_path)
    source = drop(layout.inbox, spec_with("pipeok", read_op("get_item"), read_op("get_other", path="/other/{item_id}")))
    outcome = process(source, layout)

    assert outcome.status == "generated", outcome.detail
    assert outcome.tools == ["pipeok__get_item", "pipeok__get_other"]
    for p in (layout.specs / "pipeok.yaml", layout.servers / "pipeok_server.py", layout.tests / "test_pipeok.py"):
        assert p.exists(), p
    assert (layout.inbox / "done" / source.name).exists() and not source.exists()
    assert not (layout.inbox / ".staging" / "pipeok").exists(), "staging must be cleaned up"
    # the promoted files are exactly what the generator produces from the promoted spec
    assert generate(layout.specs / "pipeok.yaml", layout.servers, layout.tests, check=True) == []
    assert "GENERATED by generators/from_spec.py" in (layout.servers / "pipeok_server.py").read_text(encoding="utf-8")


# -- failures are reported, rolled back, never silent --------------------------------------------

def test_a_spec_whose_own_tests_fail_is_rolled_back_and_never_promoted(tmp_path):
    layout = layout_in(tmp_path)
    bad = make_operation(
        name="get_item", summary="Fetch one record by id.", when_to_call="Call when you know the record id.",
        method="GET", path="/items/{item_id}",
        params=[make_param("item_id", "integer", "path", True, "The record id.")],
        response_type="object", response_description="The record with an id field.",
        examples=[ok_example({"item_id": 1}, {"id": 1}, ["this_key_is_not_in_the_mock"])],  # generated test must go red
        source="openapi", confidence=0.95)
    source = drop(layout.inbox, spec_with("pipebad", bad))
    outcome = process(source, layout)

    assert outcome.status == "failed" and "nothing was promoted" in outcome.detail
    assert not any(layout.specs.iterdir()) and not any(layout.servers.iterdir()) and not any(layout.tests.iterdir())
    assert (layout.inbox / "failed" / source.name).exists()
    assert "staged verification failed" in (layout.inbox / "failed" / f"{source.stem}.reason.txt").read_text(encoding="utf-8")
    assert not (layout.inbox / ".staging" / "pipebad").exists()


def test_existing_server_is_never_overwritten(tmp_path):
    layout = layout_in(tmp_path)
    (layout.servers / "pipedup_server.py").write_text("# hand written\n", encoding="utf-8")
    outcome = process(drop(layout.inbox, spec_with("pipedup", read_op())), layout)
    assert outcome.status == "failed" and "already exists" in outcome.detail
    assert (layout.servers / "pipedup_server.py").read_text(encoding="utf-8") == "# hand written\n"


def test_schema_invalid_ingestor_output_fails_with_the_validator_message(tmp_path):
    layout = layout_in(tmp_path)
    spec = spec_with("pipeschema", read_op())
    spec["operations"][0]["bogus_field"] = 1  # additionalProperties: false
    outcome = process(drop(layout.inbox, spec), layout)
    assert outcome.status == "failed" and "invalid spec" in outcome.detail and "bogus_field" in outcome.detail
    assert not any(layout.servers.iterdir())


def test_unrecognised_file_fails_with_a_reason(tmp_path):
    layout = layout_in(tmp_path)
    junk = layout.inbox / "mystery.json"
    junk.write_text('{"nothing": "useful"}', encoding="utf-8")
    outcome = process(junk, layout)
