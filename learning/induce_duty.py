"""Phase C of the learning loop: induce a candidate DUTY from recurring successful planner runs (CLAUDE.md D23).

    python -m learning.induce_duty [--runs runs] [--proposals proposals] [--duties duties]

Reads the run records `Orchestrator(run_log_dir=...)` writes, groups the usable ones by tool sequence and, for every group
of at least MIN_RUNS runs, writes a PROPOSAL to `<proposals>/duties/`:

    <name>.duty.yaml           the proposed duty (reviewer "PROPOSED-UNREVIEWED"; a person must edit and approve it)
    <name>.duty.diff           the reviewable diff: a new file duties/<name>.yaml
    <name>.contract_test.py    the generated test that apply will install (contract_test_source)
    <name>.evidence.json       which runs, which goals, how every argument was bound

It NEVER writes to duties/ or tests/ and never installs anything: learning/apply.py does that, only for a proposal a person
moved into proposals/duties/approved/. Induction is idempotent: a group already proposed (same evidence runs) in ANY state
(pending, approved/, rejected/, applied/) is skipped, and so is a group an existing duty already answers.

A group yields NO proposal (and the reason is reported) when an argument cannot be explained: a duty that guesses an
argument is worse than none.
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:  # allow `python learning/induce_duty.py` as well as `python -m learning.induce_duty`
    sys.path.insert(0, str(ROOT))

from agent.duties import (  # noqa: E402
    DEFAULT_DUTIES_DIR, DUTY_CONFIDENCE_THRESHOLD, DutyError, DutyLibrary, match_pattern, normalize, parse_duty,
    validate_duty_data,
)

MIN_RUNS = 3  # D23: fewer identical-sequence runs than this produce nothing. Change only with CLAUDE.md D23.
UNREVIEWED = "PROPOSED-UNREVIEWED"
STATES = ("", "approved", "rejected", "applied")  # where a proposal can be (below proposals/duties/)
_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
_MISSING = object()


@dataclass
class Outcome:
    name: str | None  # the proposed duty's name; None when nothing was proposed
    sequence: list[str]
    status: str  # "proposed" | "skipped"
    reason: str = ""
    runs: list[str] = field(default_factory=list)


class _Skip(Exception):
    """This group yields no proposal; the message is the reason."""


def contract_test_source(name: str) -> str:
    """The text of the generated contract test for duties/<name>.yaml. apply installs exactly this."""
    return (
        f"# GENERATED by learning/induce_duty.py for duties/{name}.yaml: DO NOT EDIT (CLAUDE.md D23)\n"
        f'"""The duty {name!r} keeps its contract: it replays its own example alone, through the real orchestrator, with a\n'
        f'model that fails the test if it is consulted (tests/duty_contract.py). The duties directory is read from the\n'
        f'environment variable DUTIES_DIR (default: duties/)."""\n'
        f"import duty_contract\n"
        f"\n"
        f"\n"
        f"async def test_duty_contract_{name}():\n"
        f'    await duty_contract.check_duty_contract("{name}")\n'
    )


# -- reading evidence ----------------------------------------------------------------------------------------------

def load_runs(runs_dir: Path) -> list[tuple[str, dict[str, Any]]]:
    out = []
    for path in sorted(Path(runs_dir).glob("*.json")) if Path(runs_dir).is_dir() else []:
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(record, dict):
            out.append((path.name, record))
    return out


def is_evidence(record: dict[str, Any]) -> bool:
    """D23 (1): done by the planner (not by a duty), successful, and every operation succeeded."""
    ops = record.get("operations")
    return (record.get("success") is True and record.get("duty_used") is None and isinstance(ops, list) and bool(ops)
            and all(isinstance(o, dict) and o.get("ok") is True for o in ops) and isinstance(record.get("goal"), str))


def _proposal_dir(proposals_dir: Path) -> Path:
    return Path(proposals_dir) / "duties"


def _existing_proposals(proposals_dir: Path) -> tuple[set[str], list[set[str]]]:
    """(names, evidence run-file sets) of every proposal in any state."""
    names: set[str] = set()
    evidence: list[set[str]] = []
    base = _proposal_dir(proposals_dir)
    for state in STATES:
        folder = base / state if state else base
        if not folder.is_dir():
            continue
        for p in folder.glob("*.duty.yaml"):
            names.add(p.name[: -len(".duty.yaml")])
        for p in folder.glob("*.evidence.json"):
            names.add(p.name[: -len(".evidence.json")])
            try:
                evidence.append(set(json.loads(p.read_text(encoding="utf-8")).get("runs", [])))
            except (OSError, ValueError, AttributeError):
                pass
    return names, evidence


# -- the pattern ---------------------------------------------------------------------------------------------------

def build_pattern(goals: list[str]) -> tuple[str, list[list[str]]]:
    """(pattern, captures). The pattern is the words common to every goal, in sequence, with `{slot0}`, `{slot1}`... where
    they differ; captures[run][slot] is the text each run had there (possibly several words)."""
    toks = [normalize(g).split() for g in goals]
    ref = toks[0]
    maps: list[dict[int, int]] = [{i: i for i in range(len(ref))}]
    common = set(range(len(ref)))
    for other in toks[1:]:
        m: dict[int, int] = {}
        for block in difflib.SequenceMatcher(None, ref, other, autojunk=False).get_matching_blocks():
            for k in range(block.size):
                m[block.a + k] = block.b + k
        maps.append(m)
        common &= set(m)
    kept = sorted(common)
    if not kept:
        raise _Skip("the goals share no word, so there is no pattern to learn")
    words: list[str] = []
    captures: list[list[str]] = [[] for _ in goals]
    for g in range(len(kept) + 1):
        texts = []
        for r, t in enumerate(toks):
            lo = maps[r][kept[g - 1]] + 1 if g else 0
            hi = maps[r][kept[g]] if g < len(kept) else len(t)
            texts.append(" ".join(t[lo:hi]))
        if all(texts) and len(set(texts)) > 1:
            words.append("{slot%d}" % (len([w for w in words if w.startswith("{slot")])))
            for r, text in enumerate(texts):
                captures[r].append(text)
        elif any(texts) and not all(t == texts[0] for t in texts):
            raise _Skip("the goals differ by optional words (a region present in some goals and empty in others)")
        elif texts[0]:
            words.extend(texts[0].split())  # the same text in every goal: part of the pattern
        if g < len(kept):
            words.append(ref[kept[g]])
    return " ".join(words), captures


# -- binding the arguments -----------------------------------------------------------------------------------------

def _bare(tool: str) -> str:
    return tool.split("__", 1)[-1]


def _step_ids(tools: list[str]) -> list[str]:
    ids: list[str] = []
    for tool in tools:
        base = re.sub(r"[^a-z0-9_]", "_", _bare(tool).lower()) or "step"
        if not base[0].isalpha():
            base = "s" + base
        if base == "intent":
            base = "intent_step"
        candidate, n = base, 1
        while candidate in ids:
            n += 1
            candidate = f"{base}_{n}"
        ids.append(candidate)
    return ids


def _paths(node: Any, target: Any, prefix: tuple[str, ...] = (), depth: int = 0) -> list[tuple[str, ...]]:
    """Every path in a result (dict keys, list indexes) whose value equals `target` (same JSON type)."""
    found: list[tuple[str, ...]] = []
    if type(node) is type(target) and node == target:
        found.append(prefix)
    if depth >= 6:
        return found
    if isinstance(node, dict):
        for k, v in node.items():
            if isinstance(k, str) and k and "." not in k:
                found += _paths(v, target, prefix + (k,), depth + 1)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            found += _paths(v, target, prefix + (str(i),), depth + 1)
    return found


def _walk(node: Any, path: tuple[str, ...]) -> Any:
    for seg in path:
        if isinstance(node, dict) and seg in node:
            node = node[seg]
        elif isinstance(node, list) and seg.isdigit() and int(seg) < len(node):
            node = node[int(seg)]
        else:
            return _MISSING
    return node


def _has_dollar(value: Any) -> bool:
    return isinstance(value, str) and value.startswith("$")


def _slot_names(order: list[tuple[int, str]], count: int) -> list[str]:
    """Name each slot after the first argument that uses it; unused ones are slot1, slot2... (deterministic)."""
    names: dict[int, str] = {}
    taken: set[str] = set()
    for slot, arg in order:
        if slot in names:
            continue
        base = re.sub(r"[^a-z0-9_]", "_", arg.lower())
        if not _NAME.match(base):
            continue
        name, n = base, 1
        while name in taken:
            n += 1
            name = f"{base}_{n}"
        names[slot] = name
        taken.add(name)
    for slot in range(count):
        if slot not in names:
            n = slot + 1
            while f"slot{n}" in taken:
                n += 1
            names[slot] = f"slot{n}"
            taken.add(names[slot])
    return [names[i] for i in range(count)]


def _bind_steps(group: list[dict[str, Any]], captures: list[list[str]], n_slots: int):
    tools = [o["tool"] for o in group[0]["operations"]]
    ids = _step_ids(tools)
    raw_steps: list[dict[str, Any]] = []  # args hold ("slot", i) markers until slots are named
    uses: list[tuple[int, str]] = []
    bindings: list[dict[str, Any]] = []
    for i, tool in enumerate(tools):
        keys: list[str] = []
        for run in group:
            for k in run["operations"][i].get("arguments") or {}:
                if k not in keys:
                    keys.append(k)
        args: dict[str, Any] = {}
        for key in keys:
            where = f"step {ids[i]} ({tool}), argument {key!r}"
            vals = [(run["operations"][i].get("arguments") or {}).get(key, _MISSING) for run in group]
            if any(v is _MISSING for v in vals):
                raise _Skip(f"{where}: present in only some of the runs")
            if any(not isinstance(v, (str, int, float, bool)) for v in vals):
                raise _Skip(f"{where}: a list, object or null, which a duty argument cannot hold")
            scalar = not any(isinstance(v, bool) for v in vals)
            bound: Any = _MISSING
            source = ""
            if scalar:
                for s in range(n_slots):  # (a) the text of a placeholder in the goal, in every run
                    if all(str(v) == captures[r][s] for r, v in enumerate(vals)):
                        bound, source = ("slot", s), "intent"
                        uses.append((s, key))
                        break
            if bound is _MISSING and scalar:  # (b) a value of an EARLIER step's result, at the same path in every run
                best = None
                for j in range(i):
                    results = [run["operations"][j].get("result") for run in group]
                    for path in _paths(results[0], vals[0]):
                        if all(type(w) is type(v) and w == v for w, v in zip((_walk(res, path) for res in results), vals)):
                            rank = (len(path), -j, path)
                            if best is None or rank < best[0]:
                                best = (rank, j, path)
                if best is not None:
                    _, j, path = best
                    bound, source = "$" + ".".join([ids[j], *best[2]]), "result"
            if bound is _MISSING:  # (c) the same literal in every run
                if all(type(v) is type(vals[0]) and v == vals[0] for v in vals):
                    if _has_dollar(vals[0]):
                        raise _Skip(f"{where}: the literal {vals[0]!r} starts with $, which a duty reads as a reference")
                    bound, source = vals[0], "literal"
                else:  # (d)
                    raise _Skip(f"{where}: differs between runs ({_show(vals)}) and is neither part of the goal nor a "
                                "value found in an earlier step's result")
            args[key] = bound
            bindings.append({"step": ids[i], "argument": key, "source": source, "value": bound if source != "intent" else bound})
        raw_steps.append({"id": ids[i], "tool": tool, "args": args})
    return raw_steps, uses, bindings, ids


def _show(vals: list[Any]) -> str:
    text = ", ".join(repr(v) for v in vals[:3])
    return text if len(text) <= 80 else text[:77] + "..."


# -- one group -----------------------------------------------------------------------------------------------------

def _build(group: list[dict[str, Any]], name_for, duties_dir: Path) -> tuple[str, dict[str, Any], list[dict[str, Any]]]:
    tools = [o["tool"] for o in group[0]["operations"]]
    writes = [any(run["operations"][i].get("read_only") is not True for run in group) for i in range(len(tools))]
    if not any(writes):
        raise _Skip("a duty needs a write boundary: every step of this sequence is read-only")
    boundary, last_write = writes.index(True), len(writes) - 1 - writes[::-1].index(True)
    pattern, captures = build_pattern([run["goal"] for run in group])
    n_slots = len(captures[0])
    steps, uses, bindings, ids = _bind_steps(group, captures, n_slots)
    names = _slot_names(uses, n_slots)
    for step in steps:
        step["args"] = {k: (f"$intent.{names[v[1]]}" if isinstance(v, tuple) else v) for k, v in step["args"].items()}
    for b in bindings:
        if b["source"] == "intent":
            b["value"] = f"$intent.{names[b['value'][1]]}"
    pattern = re.sub(r"\{slot(\d+)\}", lambda m: "{%s}" % names[int(m.group(1))], pattern)

    results = [run["operations"][last_write].get("result") for run in group]
    sid = ids[last_write]
    statuses = [r.get("status") if isinstance(r, dict) else None for r in results]
    if all(isinstance(s, str) for s in statuses) and len(set(statuses)) == 1:
        success = {"name": f"{sid}_succeeded", "check": f"${sid}.status", "equals": statuses[0]}
    elif all(r is True for r in results):
        success = {"name": f"{sid}_succeeded", "check": f"${sid}", "equals": True}
    elif all(r not in (None, False, "", [], {}) for r in results):
        success = {"name": f"{sid}_succeeded", "check": f"${sid}"}
    else:
        raise _Skip(f"step {sid} (the last write) has no result a success criterion can test")

    name = name_for(tools[boundary])
    runs_text = f"{len(group)} successful planner runs"
    data = {
        "name": name,
        "description": f"Learned from {runs_text}: " + ", ".join(_bare(t) for t in tools) + ".",
        "review": {"status": "reviewed", "reviewer": UNREVIEWED},
        "intent_patterns": [pattern],
        "parameters": {n: {"type": "string"} for n in names},
        "steps": steps,
        "write_boundary": {"before": ids[boundary]},
        "success": success,
        "example": {"intent": group[0]["goal"], "expect": "success"},
    }
    try:
        validate_duty_data(data, duties_dir)
        duty = parse_duty(data)
    except DutyError as exc:
        raise _Skip(f"the proposed duty is not valid: {exc}") from exc
    match = match_pattern(duty, pattern, group[0]["goal"])
    if match is None or match.confidence != 1.0:
        raise _Skip("the proposed pattern does not match its own example goal exactly")
    return name, data, bindings


def _write(folder: Path, name: str, data: dict[str, Any], files: list[str], group_goals: list[str], tools: list[str],
           bindings: list[dict[str, Any]]) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000)
    diff = "".join(difflib.unified_diff([], text.splitlines(keepends=True), fromfile="/dev/null",
                                        tofile=f"duties/{name}.yaml"))
    header = f"# proposed from {len(files)} runs: {', '.join(files)}\n"
    evidence = {"runs": files, "tool_sequence": tools, "goals": group_goals, "bindings": bindings}
    for suffix, content in ((".duty.yaml", text), (".duty.diff", header + diff), (".contract_test.py", contract_test_source(name)),
                            (".evidence.json", json.dumps(evidence, indent=2, default=str) + "\n")):
        (folder / f"{name}{suffix}").write_text(content, encoding="utf-8", newline="\n")


def induce(runs_dir: Path, proposals_dir: Path, duties_dir: Path = DEFAULT_DUTIES_DIR, *,
           threshold: float = DUTY_CONFIDENCE_THRESHOLD) -> list[Outcome]:
    runs_dir, proposals_dir, duties_dir = Path(runs_dir), Path(proposals_dir), Path(duties_dir)
    groups: dict[tuple[str, ...], list[tuple[str, dict[str, Any]]]] = {}
    for filename, record in load_runs(runs_dir):
        if is_evidence(record):
            groups.setdefault(tuple(o.get("tool", "") for o in record["operations"]), []).append((filename, record))
    library = DutyLibrary(duties_dir)
    proposed_names, proposed_evidence = _existing_proposals(proposals_dir)
    taken = set(proposed_names) | {p.stem for p in duties_dir.glob("*.yaml")} if duties_dir.is_dir() else set(proposed_names)
    outcomes: list[Outcome] = []
    for sequence, members in groups.items():
        seq, files = list(sequence), [f for f, _ in members]
        if len(members) < MIN_RUNS:
            outcomes.append(Outcome(None, seq, "skipped", f"skipped: {len(members)} of {MIN_RUNS} runs", files))
            continue
        records = [r for _, r in members]
        goal = records[0]["goal"]
        hit = next((m for m in library.candidates(goal) if m.confidence >= threshold), None)
        if hit is not None:
            outcomes.append(Outcome(None, seq, "skipped", f"duty {hit.duty.name!r} already matches the goal "
                                    f"{goal!r} (confidence {hit.confidence})", files))
            continue
        if any(set(files) & ev for ev in proposed_evidence):
            outcomes.append(Outcome(None, seq, "skipped", "already proposed from these runs (a proposal exists in "
                                    "proposals/duties/, in some state)", files))
            continue

        def name_for(tool: str) -> str:
            base = re.sub(r"[^a-z0-9_]", "_", _bare(tool).lower())
            if not _NAME.match(base):
                base = "duty_" + base
            name, n = base, 1
            while name in taken:
                n += 1
                name = f"{base}_{n}"
            return name

        try:
            name, data, bindings = _build(records, name_for, duties_dir)
        except _Skip as exc:
            outcomes.append(Outcome(None, seq, "skipped", str(exc), files))
            continue
        taken.add(name)
        proposed_evidence.append(set(files))
        _write(_proposal_dir(proposals_dir), name, data, files, [r["goal"] for r in records], seq, bindings)
        outcomes.append(Outcome(name, seq, "proposed", f"{len(files)} runs", files))
    return outcomes


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runs", type=Path, default=Path("runs"))
    ap.add_argument("--proposals", type=Path, default=Path("proposals"))
    ap.add_argument("--duties", type=Path, default=DEFAULT_DUTIES_DIR)
    args = ap.parse_args(argv)
    outcomes = induce(args.runs, args.proposals, args.duties)
    for o in outcomes:
        seq = " -> ".join(o.sequence)
        if o.status == "proposed":
            print(f"[PROPOSED] {o.name} ({seq}): {o.reason}; written to {_proposal_dir(args.proposals)}")
        else:
            print(f"[SKIPPED ] {seq}: {o.reason}")
    if not outcomes:
        print("no usable runs (a run is evidence only if the planner did it and every operation succeeded)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
